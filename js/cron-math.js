export const WORKFLOW_PATH = '.github/workflows/render-awake.yml';

export function parseRepository(input) {
  let value = input.trim();
  if (value.startsWith('https://')) {
    if (!/^https:\/\/github\.com\/[^/?#]+\/[^/?#]+\/?$/i.test(value)) throw new Error('Use owner/repo or a GitHub repository URL.');
    value = value.replace(/^https:\/\/github\.com\//i, '');
  }
  value = value.replace(/\/$/, '').replace(/\.git$/, '');
  const parts = value.split('/');
  if (parts.length !== 2 || !/^[a-z\d](?:[a-z\d-]{0,37}[a-z\d])?$/i.test(parts[0]) || parts[0].includes('--') || !/^[a-z\d_.-]{1,100}$/i.test(parts[1]) || /^\.{1,2}$/.test(parts[1])) {
    throw new Error('Enter a valid GitHub owner/repo.');
  }
  return parts.join('/');
}

export function validateBranch(input) {
  const value = input.trim();
  if (!value || value === '@' || value.startsWith('-') || /[\x00-\x20\x7f~^:?*\[\\]/.test(value) || value.includes('..') || value.includes('@{') || value.endsWith('.') || value.split('/').some(part => !part || part.startsWith('.') || part.endsWith('.lock'))) {
    throw new Error('Enter a valid Git branch name.');
  }
  return value;
}

export function validateServiceUrl(input) {
  if (/[\x00-\x20\x7f]/.test(input) || /%0[ad]/i.test(input) || input.includes('\\') || input.includes('${{')) throw new Error('URL contains unsafe characters.');
  let url;
  try { url = new URL(input); } catch { throw new Error('Enter a complete HTTPS URL.'); }
  if (!/^https:\/\//i.test(input) || url.protocol !== 'https:' || !url.hostname || url.username || url.password || url.hash) throw new Error('Use HTTPS without credentials or a fragment.');
  return url.href;
}

export function createSchedule({ interval = 10, hours = 24, start = 8, timezone = 'UTC' } = {}) {
  if (![10, 12, 14].includes(interval) || ![12, 16, 24].includes(hours) || !Number.isInteger(start) || start < 0 || start > 23 || !['UTC', 'Asia/Kolkata'].includes(timezone)) throw new Error('Invalid schedule configuration.');
  const range = (a, b) => a === b ? `${a}` : `${a}-${b}`;
  const end = start + hours - 1;
  const windows = hours === 24 ? ['*'] : end < 24 ? [range(start, end)] : [range(start, 23), range(0, end % 24)];
  return windows.map(window => ({ cron: `*/${interval} ${window} * * *`, timezone }));
}

export function generateWorkflow(config) {
  const url = validateServiceUrl(config.url);
  const schedule = createSchedule(config).map(entry => `    - cron: '${entry.cron}'\n      timezone: '${entry.timezone}'`).join('\n');
  return `# Generated by Render Awake
# https://automate-workflow.github.io/render-awake/
# Maintained by Automate-Workflow
# https://github.com/Automate-Workflow

name: Keep Render Service Awake

on:
  schedule:
${schedule}
  workflow_dispatch:

permissions:
  contents: read

jobs:
  keep-awake:
    runs-on: ubuntu-latest
    timeout-minutes: 2

    steps:
      - name: Ping Render service
        env:
          RENDER_URL: ${JSON.stringify(url)}
        shell: bash
        run: |
          if ! status=$(curl --location --silent \\
            --proto '=https' --proto-redir '=https' \\
            --output /dev/null \\
            --write-out "%{http_code}" \\
            --connect-timeout 15 --max-time 60 \\
            -- "$RENDER_URL"); then
            echo "Request failed or timed out."
            exit 1
          fi

          echo "HTTP status: $status"
          if [ "$status" != "200" ]; then
            echo "Health check failed."
            exit 1
          fi
          echo "Render service responded successfully."
`;
}

export function githubFileUrl(repository, branch) {
  const repo = parseRepository(repository);
  const ref = encodeURIComponent(validateBranch(branch));
  return `https://github.com/${repo}/new/${ref}?${new URLSearchParams({ filename: WORKFLOW_PATH })}`;
}
